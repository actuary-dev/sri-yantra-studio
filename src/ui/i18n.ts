const DICTS: Record<Lang, Record<TKey, string>> = { en, hi };

export type TFn = (key: TKey, vars?: Record<string, string | number>) => string;

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  let s: string = DICTS[lang][key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Non-hook translation using the current language. */
export const t: TFn = (key, vars) => translate(studio.getState().settings.lang, key, vars);

export function useLang(): Lang {
  return useStudio((s) => s.settings.lang);
}

export function useT(): TFn {
  const lang = useLang();
  return useCallback<TFn>((key, vars) => translate(lang, key, vars), [lang]);
}
